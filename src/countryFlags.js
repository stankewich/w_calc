/**
 * Maps country names (in Russian) to Unicode flag emoji.
 *
 * Uses Regional Indicator Symbols: each letter of ISO 3166-1 alpha-2 code
 * is converted to a Regional Indicator (A=U+1F1E6, B=U+1F1E7, etc.).
 * Two indicators together render as a flag emoji.
 *
 * @param {string} countryName - Country name in Russian (any case form)
 * @returns {string} Flag emoji like "🇳🇱", or empty string if unknown
 */
export function getCountryFlag(countryName) {
  var code = COUNTRY_ISO[countryName];
  if (!code) return '';
  return isoToFlagEmoji(code);
}

/**
 * Converts a 2-letter ISO 3166-1 alpha-2 code to a Unicode flag emoji.
 * @param {string} iso - Two-letter country code, e.g. "NL", "CA"
 * @returns {string} Flag emoji
 */
export function isoToFlagEmoji(iso) {
  if (iso === 'ENGLAND') return '\u{1F3F4}\u{E0067}\u{E0062}\u{E0065}\u{E006E}\u{E0067}\u{E007F}';
  if (iso === 'SCOTLAND') return '\u{1F3F4}\u{E0067}\u{E0062}\u{E0073}\u{E0063}\u{E0074}\u{E007F}';
  if (iso === 'WALES') return '\u{1F3F4}\u{E0067}\u{E0062}\u{E0077}\u{E006C}\u{E0073}\u{E007F}';
  if (iso === 'NIR') return '\u{1F3F4}\u{E0067}\u{E0062}\u{E006E}\u{E0069}\u{E0072}\u{E007F}';
  var upper = iso.toUpperCase();
  return String.fromCodePoint(
    0x1F1E6 + upper.charCodeAt(0) - 65,
    0x1F1E6 + upper.charCodeAt(1) - 65
  );
}

